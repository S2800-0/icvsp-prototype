"""Accuracy with and without the device decision logic, per class, on the held-out Cairo videos.

Raw    = every detection of the model (confidence >= 0.25), scored as before (>= 2 hits near the hazard).
Logic  = the same detections passed through the firmware's HazardTracker (road check, 3-of-5 frames,
         motion check for speed bumps), compiled from firmware/lib/icvsp_core; each confirmed hazard is one
         report, scored with >= 1 report near the hazard.
False reports = groups of reports away from every tagged hazard of that class (same grouping as raw).

The videos come from a forward-facing camera, so the tracker runs with --forward. The detections were
saved at 15 frames per second; GPS speed is not known for YouTube footage, so the car is assumed moving.

    cd firmware && python tools/score_logic.py          # writes results/logic_accuracy.md

Needs a C++17 compiler and the detection files in ai/runs (not in git: made from private videos).
"""
import re, subprocess, sys
from pathlib import Path

FW = Path(__file__).resolve().parents[1]
AI = FW.parent / 'ai'
BIN = FW / '.pio' / 'replay_detections'

VIDEOS = [  # name, minutes, events file, detection folder prefix
    ('Night (Cairo, held out)', 10, AI / 'data/egypt_test/external/events_cairo.csv', 'cairo'),
    ('Day (Cairo, held out)', 18, AI / 'data/egypt_test/external/events_cairo_yt_02.csv', 'day'),
]
MODELS = [('YOLO11n v3c (reference)', 'v3c'), ('YOLO11n v4, epoch 80 (+ public Kaggle data)', 'v4last'),
          ('YOLO11n v5, epoch 80 (curated public data)', 'v5last'),
          ('YOLO11n v4, epoch 1 (saved as best)', 'v4'),
          ('ESPDet-Pico (chip model)', 'espdet224'), ('ESPDet-Pico v5 (chip model, curated data)', 'espdet224v5')]


def build():
    src = FW / 'lib/icvsp_core/src'
    BIN.parent.mkdir(exist_ok=True)
    subprocess.run(['c++', '-std=c++17', '-O2', f'-I{src}', str(FW / 'tools/replay_detections.cpp'),
                    str(src / 'hazard_tracker.cpp'), str(src / 'bump_detector.cpp'), '-o', str(BIN)], check=True)


def score(dets: Path, events: Path, min_hits: int):
    out = subprocess.run([sys.executable, str(AI / 'scripts/event_recall.py'), str(dets), str(events),
                          '--min-hits', str(min_hits)], capture_output=True, text=True, check=True).stdout
    rec = {c: re.search(rf'{c}\s+(\d+)/(\d+)', out) for c in ('speed_bump', 'pothole')}
    false = {}
    for c in ('speed_bump', 'pothole'):
        m = re.search(rf'· {c}: (.*)', out)
        false[c] = len(m.group(1).split('), ')) if m else 0
    return {c: (int(rec[c].group(1)), int(rec[c].group(2))) if rec[c] else (0, 0) for c in rec}, false


def main():
    build()
    rows = []
    for vname, minutes, events, prefix in VIDEOS:
        for mname, tag in MODELS:
            raw = AI / 'runs' / f'{prefix}_{tag}' / 'detections.csv'
            if not raw.exists():
                continue
            logic = raw.with_name('detections_device_logic.csv')
            logic.write_text(subprocess.run([str(BIN), str(raw), '--fps', '15', '--forward'],
                                            capture_output=True, text=True, check=True).stdout)
            for label, path, hits in (('raw detections', raw, 2), ('with device logic', logic, 1)):
                rec, false = score(path, events, hits)
                rows.append((vname, mname, label, rec, false, minutes))

    lines = ['# Detection accuracy with the device decision logic', '',
             'Generated by `firmware/tools/score_logic.py`. Held-out Cairo videos (forward-facing camera, never used '
             'for training). *Found* = tagged hazards flagged while approaching them. *False / min* = groups of '
             'reports away from every tagged hazard of that class, per minute of video.', '',
             '| Video | Model | | Speed bumps found | Speed bump false / min | Potholes found | Pothole false / min |',
             '|---|---|---|---|---|---|---|']
    for v, m, label, rec, false, minutes in rows:
        b, p = rec['speed_bump'], rec['pothole']
        lines.append(f'| {v} | {m} | {label} | {b[0]} / {b[1]} | {false["speed_bump"] / minutes:.2f} | '
                     f'{p[0]} / {p[1]} | {false["pothole"] / minutes:.2f} |')
    out = FW / 'results' / 'logic_accuracy.md'
    out.parent.mkdir(exist_ok=True)
    out.write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
