"""Fleet slowing (FR-28) on and off, every scenario, several seeds. Simulated drivers brake at speed bumps, some at
potholes, and some slow down or stop at two crossings with no hazard (one is where the attackers' fake bump is).

    python3 sil/compare_fleet_slowing.py --seeds 5     # -> sil/results/fleet_slowing.md
"""
from __future__ import annotations

import argparse
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import run_sil  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--cars", type=int, default=40)
    a = ap.parse_args()
    run_sil.build()
    lines = ["# Fleet slowing as supporting evidence (FR-28)", "",
             f"Generated by `sil/compare_fleet_slowing.py --seeds {a.seeds}`. Mean (min to max) over seeds 1..{a.seeds}, "
             f"{a.cars} cars, camera profile `assumed`. Drivers brake at every speed bump, half of them at potholes, and "
             "half slow down (a fifth stop) at two crossings with no hazard, one at the attackers' fake speed bump. "
             "*Warned* = real hazards warned 300 m ahead after the first 10 minutes; *false alert* = share of hazard "
             "queries that showed any false advisory or warning.", "",
             "| Scenario | Fleet slowing | Warned | False warnings | Any false alert |", "|---|---|---|---|---|"]
    for name in run_sil.SCENARIOS:
        for on in (False, True):
            w, fw, fa = [], [], []
            for seed in range(1, a.seeds + 1):
                scn = run_sil.SCENARIOS[name]
                scn.cars = a.cars
                r = run_sil.simulate(scn, seed, "assumed", fleet_slowing=on)
                w.append(r["warned_real_after_10min"]); fw.append(r["queries_with_false_warning"])
                fa.append(r["queries_with_false_advisory_or_warning"])
            f = lambda v: f"{100 * statistics.mean(v):.0f} % ({100 * min(v):.0f}–{100 * max(v):.0f})"  # noqa: E731
            lines.append(f"| {run_sil.SCENARIOS[name].title.split(':')[0]} | {'on' if on else 'off'} | {f(w)} | "
                         f"{f(fw)} | {f(fa)} |")
            print(lines[-1], flush=True)
    out = run_sil.ROOT / "sil" / "results" / "fleet_slowing.md"
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
