"""Whole-chain simulation with each camera model's measured hit and false-report rates (CAMERAS in run_sil.py),
to see whether the choice of camera model changes what drivers get.

    python3 sil/compare_cameras.py            # all scenarios, 40 cars -> sil/results/camera_comparison.md
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import run_sil  # noqa: E402

PROFILES = ["none", "espdet_3of5", "espdet", "v5_3of5", "v5", "v3c", "v4"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cars", type=int, default=40)
    ap.add_argument("--seed", type=int, default=1)
    a = ap.parse_args()
    run_sil.build()
    pct = lambda x: "–" if x != x else f"{100 * x:.0f} %"  # noqa: E731
    lines = ["# Camera model comparison in the system simulation", "",
             f"Generated by `sil/compare_cameras.py --cars {a.cars} --seed {a.seed}`. Same cars, hazards, IMU and "
             "network as `run_sil.py`; only the camera changes. Camera rates are measured after the device logic "
             "on the held-out Cairo videos (see `CAMERAS` in `run_sil.py`; small samples). Camera-only reports have "
             "no measured size, so they can raise an advisory at most (FR-27).", "",
             "| Scenario | Camera | Real hazards: warned (after 10 min) | advisory only | False warnings | "
             "Queries showing any false alert (advisory or warning) | Reports accepted |",
             "|---|---|---|---|---|---|---|"]
    for name in run_sil.SCENARIOS:
        for cam in PROFILES:
            scn = run_sil.SCENARIOS[name]
            scn.cars = a.cars
            print(f"{name} / {cam} ...", flush=True)
            r = run_sil.simulate(scn, a.seed, cam)
            lines.append(f"| {r['title'].split(':')[0]} | {cam} | {pct(r['warned_real_after_10min'])} | "
                         f"{pct(r['advisory_real'])} | {pct(r['queries_with_false_warning'])} | "
                         f"{pct(r['queries_with_false_advisory_or_warning'])} | {r['reports']['accepted']} |")
    out = run_sil.ROOT / "sil" / "results" / "camera_comparison.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
