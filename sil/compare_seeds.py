"""Camera profiles compared over several random seeds (one seed is too noisy: each profile draws different cars).

    python3 sil/compare_seeds.py --seeds 5     # -> sil/results/camera_seeds.md
"""
from __future__ import annotations

import argparse
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import run_sil  # noqa: E402

PROFILES = ["none", "espdet_3of5", "espdet", "v5_3of5", "v5"]
SCENARIOS = ["fleet", "faults"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--cars", type=int, default=40)
    a = ap.parse_args()
    run_sil.build()
    lines = ["# Camera models over several seeds", "",
             f"Generated by `sil/compare_seeds.py --seeds {a.seeds}`. Mean (min to max) over seeds 1..{a.seeds}, "
             f"{a.cars} cars. *Warned* = real hazards warned 300 m ahead after the first 10 minutes; *false alert* = "
             "share of hazard queries that showed any false advisory or warning. `_3of5` = device logic before the "
             "pothole rule.", "",
             "| Scenario | Camera | Warned | False warnings | Any false alert |", "|---|---|---|---|---|"]
    for name in SCENARIOS:
        for cam in PROFILES:
            w, fw, fa = [], [], []
            for seed in range(1, a.seeds + 1):
                scn = run_sil.SCENARIOS[name]
                scn.cars = a.cars
                r = run_sil.simulate(scn, seed, cam)
                w.append(r["warned_real_after_10min"]); fw.append(r["queries_with_false_warning"])
                fa.append(r["queries_with_false_advisory_or_warning"])
            f = lambda v: f"{100 * statistics.mean(v):.0f} % ({100 * min(v):.0f}–{100 * max(v):.0f})"  # noqa: E731
            lines.append(f"| {run_sil.SCENARIOS[name].title.split(':')[0]} | {cam} | {f(w)} | {f(fw)} | {f(fa)} |")
            print(lines[-1], flush=True)
    out = run_sil.ROOT / "sil" / "results" / "camera_seeds.md"
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
